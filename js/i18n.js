/**
 * Controller de Internacionalização
 */
class SollosI18n {
  constructor() {
    this.currentLang = localStorage.getItem('sollos-lang') || 'pt';
    this.data = SOLLOS_I18N_DATA;
    this.services = SOLLOS_SERVICES_I18N;
  }

  init() {
    this.applyLanguage(this.currentLang);
    this.initLangToggle();
  }

  initLangToggle() {
    const toggleBtn = document.getElementById('langToggleBtn');
    if (!toggleBtn) return;

    toggleBtn.addEventListener('click', () => {
      const nextLang = this.currentLang === 'pt' ? 'en' : 'pt';
      this.setLanguage(nextLang);
    });
  }

  setLanguage(lang) {
    if (!this.data[lang]) return;
    this.currentLang = lang;
    localStorage.setItem('sollos-lang', lang);
    this.applyLanguage(lang);

    // Se o modal de serviço estiver aberto, atualiza o conteúdo no novo idioma
    if (window.sollosApp && typeof window.sollosApp.refreshActiveModal === 'function') {
      window.sollosApp.refreshActiveModal();
    }
  }

  applyLanguage(lang) {
    document.documentElement.setAttribute('lang', lang === 'pt' ? 'pt-BR' : 'en');

    // Atualiza indicadores visuais do botão de idioma
    const optPt = document.getElementById('langOptPt');
    const optEn = document.getElementById('langOptEn');
    const toggleBtn = document.getElementById('langToggleBtn');

    if (optPt && optEn) {
      if (lang === 'pt') {
        optPt.classList.add('active');
        optEn.classList.remove('active');
      } else {
        optPt.classList.remove('active');
        optEn.classList.add('active');
      }
    }

    if (toggleBtn) {
      toggleBtn.setAttribute('title', this.data[lang].lang_toggle_title);
      toggleBtn.setAttribute('aria-label', lang === 'pt' ? 'Alternar idioma para Inglês' : 'Switch language to Portuguese');
    }

    const themeBtn = document.getElementById('themeToggleBtn');
    if (themeBtn) {
      themeBtn.setAttribute('title', this.data[lang].theme_toggle_title);
      themeBtn.setAttribute('aria-label', this.data[lang].theme_toggle_title);
    }

    // 1. Textos estáticos com [data-i18n]
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (this.data[lang] && this.data[lang][key]) {
        el.innerHTML = this.data[lang][key];
      }
    });

    // 2. Placeholders com [data-i18n-placeholder]
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (this.data[lang] && this.data[lang][key]) {
        el.setAttribute('placeholder', this.data[lang][key]);
      }
    });

    // 3. Atualiza os Cards dos Serviços no Grid
    Object.keys(this.services).forEach(key => {
      const sData = this.services[key];
      const card = document.querySelector(`.service-card[data-service-trigger="${key}"]`);
      if (card) {
        const titleEl = card.querySelector('.service-title');
        const subtitleEl = card.querySelector('.service-subtitle');
        const summaryEl = card.querySelector('.service-summary');
        const tagEl = card.querySelector('.service-tag');
        const exploreEl = card.querySelector('.service-explore-link span:first-child');

        const localized = sData[lang];
        if (titleEl) titleEl.textContent = localized.shortTitle;
        if (subtitleEl) subtitleEl.textContent = localized.cardSubtitle;
        if (summaryEl) summaryEl.textContent = localized.cardSummary;
        if (tagEl) tagEl.textContent = localized.tag;
        if (exploreEl) exploreEl.textContent = this.data[lang].card_view_details;
      }
    });

    // 4. Atualiza os links de serviços no rodapé
    const footerLinks = {
      'securitizacao': lang === 'pt' ? 'Securitização' : 'Securitization',
      'build-to-suit': 'Build To Suit',
      'fusoes-aquisicoes': lang === 'pt' ? 'Fusões e Aquisições' : 'Mergers & Acquisitions',
      'due-diligence': lang === 'pt' ? 'Due Diligence' : 'Due Diligence',
      'valuation': lang === 'pt' ? 'Valuation' : 'Valuation',
      'sale-leaseback': 'Sale & Leaseback'
    };

    document.querySelectorAll('.footer-nav-link[data-service-trigger]').forEach(link => {
      const trigger = link.getAttribute('data-service-trigger');
      if (footerLinks[trigger]) {
        link.textContent = footerLinks[trigger];
      }
    });

    // 5. Atualiza opções do select de serviços no formulário
    const formSelect = document.getElementById('formService');
    if (formSelect) {
      const opts = {
        '': this.data[lang].form_opt_default,
        'securitizacao': this.data[lang].form_opt_securitizacao,
        'build-to-suit': this.data[lang].form_opt_bts,
        'fusoes-aquisicoes': this.data[lang].form_opt_ma,
        'due-diligence': this.data[lang].form_opt_dd,
        'valuation': this.data[lang].form_opt_val,
        'sale-leaseback': this.data[lang].form_opt_slb,
        'desenvolvimento-varejo': this.data[lang].form_opt_retail,
        'outro': this.data[lang].form_opt_other
      };

      Array.from(formSelect.options).forEach(opt => {
        if (opts[opt.value] !== undefined) {
          opt.textContent = opts[opt.value];
        }
      });
    }
  }

  // Retorna os dados do serviço no idioma ativo
  getServiceData(serviceKey) {
    const service = this.services[serviceKey];
    if (!service) return null;
    const localized = service[this.currentLang] || service['pt'];
    return {
      index: service.index,
      id: service.id,
      image: service.image,
      ...localized
    };
  }
}

// Inicializa no escopo global
window.sollosI18n = new SollosI18n();

